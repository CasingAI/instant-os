#!/usr/bin/env node
/**
 * Bundle listed guest npm builtins into QuickJS-eval source strings.
 * Manifest: scripts/quickjs-guest-builtins.manifest.mjs
 */
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as esbuild from 'esbuild'
import { QUICKJS_GUEST_BUILTINS } from './quickjs-guest-builtins.manifest.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const vendorScriptLabel = 'scripts/vendor-quickjs-guest-builtins.mjs'

function wrapCjsBundle(entry, bundled) {
  const label = entry.bannerLabel ?? entry.id
  const exportAssignments = entry.exportKeys
    .map((key) => `    ${key}: m.${key}`)
    .join(',\n')
  const primary = entry.primaryExport

  return `/*! Instant OS QuickJS ${label} bundle — generated by ${vendorScriptLabel}; do not edit by hand. */
(function () {
  var module = { exports: {} };
  var exports = module.exports;
  ${bundled}
  var m = module.exports;
  if (!m || typeof m.${primary} !== 'function') {
    throw new Error('Instant ${entry.id} bundle failed to expose ${primary}');
  }
  var g = typeof globalThis !== 'undefined' ? globalThis : this;
  g.${entry.globalKey} = {
${exportAssignments}
  };
})();
`
}

async function vendorEntry(entry) {
  const entryPoint = require.resolve(entry.resolveSpec)
  const result = await esbuild.build({
    entryPoints: [entryPoint],
    bundle: true,
    format: 'cjs',
    platform: 'neutral',
    target: ['es2020'],
    write: false,
    logLevel: 'warning',
  })

  const bundled = result.outputFiles?.[0]?.text
  if (!bundled) {
    throw new Error(`esbuild produced no output for ${entry.id} bundle`)
  }

  const wrapped = wrapCjsBundle(entry, bundled)
  const outPath = join(root, entry.outRelPath)
  const ts = `/* eslint-disable */
/** Generated by ${vendorScriptLabel} — do not edit by hand. */
export const ${entry.exportConstName} = ${JSON.stringify(wrapped)}
`
  writeFileSync(outPath, ts, 'utf8')
  console.log(`Wrote ${outPath} (${Math.round(wrapped.length / 1024)} KiB source)`)
}

for (const entry of QUICKJS_GUEST_BUILTINS) {
  await vendorEntry(entry)
}
