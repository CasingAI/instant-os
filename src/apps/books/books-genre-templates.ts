const FALLBACK_CATEGORY: BookCategory = '脑洞'

/** 旧分类名 / 口语别名 → 正式分类 */
const CATEGORY_ALIASES: Record<string, BookCategory> = {
  系统流: '系统',
  系统文: '系统',
  末世: '末日',
  末世文: '末日',
  囤货: '末日',
  囤货流: '末日',
  废土: '末日',
}

export function normalizeBookCategory(category: string): BookCategory {
  const trimmed = category.trim()
  const aliased = CATEGORY_ALIASES[trimmed]
  if (aliased) {
    return aliased
  }
  if ((BOOK_CATEGORIES as readonly string[]).includes(trimmed)) {
    return trimmed as BookCategory
  }
  return FALLBACK_CATEGORY
}

function hashString(value: string): number {
  let hash = 0
  for (let index = 0; index < value.length; index += 1) {
    hash = (hash * 31 + value.charCodeAt(index)) >>> 0
  }
  return hash
}

export function pickRandomGenreTemplate(category: string): GenreTemplate {
  const key = normalizeBookCategory(category)
  const pool = GENRE_TEMPLATES[key]
  return pool[Math.floor(Math.random() * pool.length)]
}

export function pickGenreTemplateForBook(category: string, bookKey: string): GenreTemplate {
  const key = normalizeBookCategory(category)
  const pool = GENRE_TEMPLATES[key]
  return pool[hashString(`${key}:${bookKey}`) % pool.length]
}

function formatList(title: string, items: string[]): string {
  if (items.length === 0) {
    return ''
  }
  return [`【${title}】`, ...items.map((item) => `- ${item}`), ''].join('\n')
}

