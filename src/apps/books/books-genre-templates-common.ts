/** 单章 2000 字标准结构（网文俱乐部） */
export const STANDARD_CHAPTER_LAYOUT = [
  '开头 100~200 字：衔接上章，点明本章主题与冲突',
  '发展 1200~1500 字：情节推进，冲突升级，压力增大',
  '高潮 300~500 字：本章爽点或冲突顶点（打脸/反转/收获）',
  '结尾 100~200 字：章末钩子，制造「非看下一章不可」的悬念',
]

/** 起承转爽（马良写作 · 最通用单章节奏） */
export const QICHENZHUANSHUANG = [
  '起（约 500 字）：简要回顾上章 + 引出本章冲突',
  '承（约 800 字）：冲突升级，压力增大，敌人或环境加码',
  '转（约 300 字）：出现转折——绝望到希望、或敌人露出底牌',
  '爽（约 400 字）：主角反击 / 真相揭晓 / 意外收获 + 钩子结尾',
]

/** 爽点三级（马良写作） */
export const PLEASURE_TIER_GUIDE = {
  small:
    '小爽点（每章至少 1 个）：路人震惊、金句回怼、小反转、小奖励解锁、技能初显。读者嘴角微微上扬即可。',
  medium:
    '中爽点（每 3~5 章 1 个）：完整打脸四部曲、关系突破、阶位跃升、谜题揭晓。读者「啊这也太爽了」。',
  large:
    '大爽点（全书/卷末 1 个）：Boss 战逆转、身份曝光连锁、多伏笔同时回收。高光时刻。',
  rhythm: '短篇 4~6 章：每章 1 个小爽点，第 3~4 章放中爽点，终章放大爽点或留开放式钩子。',
}

/** 打脸四部曲（网文666 · 飞卢天榜常用） */
export const FACE_SLAP_QUARTET = [
  '第一步·挑衅：反派主动羞辱——抢资源、当众贬低、践踏底线。越过分越好，让读者恨得牙痒。',
  '第二步·隐忍：主角不是怂，是在憋大招。微笑退让、不置可否、暗中准备。制造「反转何时来」的期待。',
  '第三步·反转：黑卡亮出、实力碾压、身份曝光、一招制敌。必须写足——全场震惊、反派崩溃、吃瓜群众目瞪口呆。',
  '第四步·余震：打脸不是结束。跪地道歉、后悔莫及、排队求饶——给爽感兜底，让读者有回甘。',
]

/** 黄金三章 · 三把锁（460.net 网文创作工程学） */
export const GOLDEN_THREE_CHAPTERS = {
  chapter1: {
    title: '第一把锁：身份认同锁（0~1000 字）',
    beats: [
      '钩子 0~100 字：从具体的、反常的动作或选择开始（动作 + 金手指/异象，瞬间建立期待）。例：「在退婚书上按下手印的下一秒，我激活了旁白系统。」',
      '困境 100~500 字：用细节而非形容词交代绝境。不写「他很穷」，写「他盯着碗里最后一口掺了沙子的饭，计算离下次救济还有三天。」',
      '破局引信 500~1000 字：困境中出现只有主角能注意到的微小变量，给出第一缕希望（金手指初现、规则漏洞、异常信息）。',
    ],
  },
  chapter2: {
    title: '第二把锁：核心期待锁（1000~2000 字）',
    beats: [
      '测试与确认 ~200 字：主角主动或被动测试第一章的「变量」，确认规则与限制（金手指边界、系统面板、能力代价）。',
      '小试牛刀 ~800 字：用新能力/新规则解决一个小麻烦，建立「这外挂有用」的读者信心。',
      '短期目标明确 ~200 字：主角确立可量化、有倒计时的近期目标（三天内、下一次比试、完成某任务）。',
    ],
  },
  chapter3: {
    title: '第三把锁：长期钩子锁（2000~3000 字）',
    beats: [
      '为目标行动 ~400 字：主角开始行动，过程显示其依然弱小，强化「逆袭」需求。',
      '意外介入与升级 ~800 字：更高级别势力/人物介入，冲突陡然升级（长老到场、神秘组织、更大赌注）。',
      '颠覆认知 ~300 字：章末抛出与前面信息矛盾或严重冲突的情报，锁住追读。例：高高在上的长老头顶标签是「被夺舍」。',
    ],
  },
}

/** 章末钩子矩阵（网文666 · 马良写作） */
export const CHAPTER_HOOK_TYPES = [
  '悬念式：「门外传来一个声音，那是一个不可能出现在这里的人。」然后本章完。',
  '反转式：整章暗示 A，最后一行发现 B 的手上有血/证据。',
  '情绪炸弹式：积蓄多章的矛盾在章末爆发，「你从来就没把我当过朋友。」直接切掉。',
  '信息投放式：章末随手扔重磅信息，「日记最后一页画着和自己一模一样的脸。」',
  '威胁型（飞卢）：「无人机上的红光，已经锁定了他的位置。」',
  '意外型（飞卢）：「门后走出来的，竟然是他。」',
]

/** 通用毒点（写作时应避免） */
export const COMMON_PITFALLS = [
  '开篇大段世界观铺垫、修炼体系介绍、人物背景——读者在第三章前划走',
  '每章节奏匀速、无爽点、无钩子——AI 最容易犯的「寡淡」错误',
  '打脸只有一句话回怼，没有挑衅→隐忍→反转→余震完整流程',
  '大段心理独白、书面化对话、车轱辘话重复同一信息',
  '铺垫超过 2 章没有任何小爽点穿插',
  '涉及真实名人造谣、越安全红线的内容',
]

export function formatCommonWebnovelGuide(): string {
  return [
    '=== 网文通用节奏（公开教程整理，各类型均需遵守） ===',
    '',
    '【单章结构 · 网文俱乐部】',
    ...STANDARD_CHAPTER_LAYOUT.map((line) => `- ${line}`),
    '',
    '【起承转爽 · 马良写作】',
    ...QICHENZHUANSHUANG.map((line) => `- ${line}`),
    '',
    '【爽点密度】',
    `- ${PLEASURE_TIER_GUIDE.small}`,
    `- ${PLEASURE_TIER_GUIDE.medium}`,
    `- ${PLEASURE_TIER_GUIDE.large}`,
    `- ${PLEASURE_TIER_GUIDE.rhythm}`,
    '',
    '【打脸四部曲 · 网文666】',
    ...FACE_SLAP_QUARTET.map((line) => `- ${line}`),
    '',
    '【黄金三章 · 460.net】',
    `- ${GOLDEN_THREE_CHAPTERS.chapter1.title}`,
    ...GOLDEN_THREE_CHAPTERS.chapter1.beats.map((b) => `  · ${b}`),
    `- ${GOLDEN_THREE_CHAPTERS.chapter2.title}`,
    ...GOLDEN_THREE_CHAPTERS.chapter2.beats.map((b) => `  · ${b}`),
    `- ${GOLDEN_THREE_CHAPTERS.chapter3.title}`,
    ...GOLDEN_THREE_CHAPTERS.chapter3.beats.map((b) => `  · ${b}`),
    '',
    '【章末钩子类型】',
    ...CHAPTER_HOOK_TYPES.map((line) => `- ${line}`),
    '',
    '【通用毒点 · 禁止】',
    ...COMMON_PITFALLS.map((line) => `- ${line}`),
  ].join('\n')
}
