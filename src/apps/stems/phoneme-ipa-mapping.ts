/** 特殊符号（CTC 标记）：不映射，直接返回空 */
const SPECIAL_SYMBOLS = new Set(['<pad>', '<s>', '</s>', '<unk>'])

/**
 * 将单个 IPA 音素符号映射为拼音。
 * 查表优先，无法识别的符号保留原样。
 */
export function ipaToPinyin(ipa: string): string {
  if (SPECIAL_SYMBOLS.has(ipa)) return ''
  // 先查声母表
  if (INITIAL_MAP[ipa] !== undefined) return INITIAL_MAP[ipa]
  // 再查韵母表
  if (FINAL_MAP[ipa] !== undefined) return FINAL_MAP[ipa]
  // 尝试带调数字模式：去掉末尾数字后的基形是否在韵母表中
  const toneMatch = ipa.match(/^(.+?)([1245])$/)
  if (toneMatch) {
    const base = toneMatch[1]
    if (FINAL_MAP[base] !== undefined) return FINAL_MAP[base]
    if (ipa in FINAL_MAP) return FINAL_MAP[ipa]
  }
  // 兜底：保留原 IPA
  return ipa
}

