// XML 消息构建
// ---------------------------------------------------------------------------

/**
 * 构建发送给 Agent 的 XML 格式消息。
 *
 * 格式：
 * ```xml
 * <alignment>
 * <lyrics>歌词原文</lyrics>
 * <phones>
 * <ph s="0.00" e="0.12" py="j" ipa="tɕ"/>
 * <ph s="0.12" e="0.18" py="ie" ipa="iɛ5"/>
 * </phones>
 * </alignment>
 * ```
 *
 * 属性：s=start(秒), e=end(秒), py=pinyin, ipa=原始IPA
 */
export function buildXmlAlignMessage(phones: AlignedPhone[], lyrics: string): string {
  const phoneLines: string[] = []

  for (const p of phones) {
    const py = ipaToPinyin(p.symbol)
    // 跳过空映射（特殊符号）
    if (!py) continue
    const s = p.start.toFixed(2)
    const e = p.end.toFixed(2)
    // XML 属性值需要转义 & 和 <
    const ipa = xmlEscape(p.symbol)
    phoneLines.push(`<ph s="${s}" e="${e}" py="${xmlEscape(py)}" ipa="${ipa}"/>`)
  }

  const lyricsEscaped = xmlEscape(lyrics)

  return `<alignment>
<lyrics>${lyricsEscaped}</lyrics>
<phones>
${phoneLines.join('\n')}
</phones>
</alignment>`
}

/** 最小 XML 转义：& < > */
function xmlEscape(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
}